    pdf = PDFReport()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    case_id = _latin1_safe(case_data.get("case_id", "CASE-REPORT-001"))
    timestamp = _latin1_safe(case_data.get("timestamp", "2026-08-22 09:00:00 UTC"))
    brand_name = _latin1_safe(case_data.get("brand_name", "Target Brand"))
    score = float(case_data.get("composite_risk_score", 85.5))
    manual_notes = _latin1_safe(case_data.get("manual_notes", ""))

    # Executive Overview
    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(10, 10, 10)
    pdf.cell(40, 6, "Case ID:", border=0)
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(60, 6, case_id, border=0)
    pdf.set_font("Helvetica", "B", 10)
    pdf.cell(40, 6, "Target Brand:", border=0)
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(50, 6, brand_name, border=0, ln=True)

    pdf.set_font("Helvetica", "B", 10)
    pdf.cell(40, 6, "Generated Date:", border=0)
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(60, 6, timestamp, border=0)
    pdf.set_font("Helvetica", "B", 10)
    pdf.cell(40, 6, "Composite Risk:", border=0)

    if score >= 75:
        pdf.set_text_color(231, 0, 11)
    elif score >= 45:
        pdf.set_text_color(217, 119, 6)
    else:
        pdf.set_text_color(16, 185, 129)

    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(50, 6, f"{score:.1f}% / 100", border=0, ln=True)
    pdf.set_text_color(10, 10, 10)
    pdf.ln(4)

    # Risk Score Breakdown Table
    pdf.set_font("Helvetica", "B", 12)
    pdf.set_text_color(10, 10, 10)
    pdf.cell(0, 8, _latin1_safe("1. Explainable Risk Score Breakdown"), ln=True)

    pdf.set_font("Helvetica", "B", 9)
    pdf.set_text_color(255, 255, 255)
    pdf.set_fill_color(30, 41, 59)
    pdf.cell(60, 6, "Evidence Layer", border=1, fill=True)
    pdf.cell(45, 6, "Dynamic Weight", border=1, fill=True)
    pdf.cell(45, 6, "Calculated Contribution", border=1, fill=True)
    pdf.cell(40, 6, "Status", border=1, fill=True, ln=True)

    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(51, 65, 85)

    breakdown = case_data.get("score_breakdown", {})
    weights = breakdown.get("weights", {})
    score_factors = breakdown

    domain_factor = score_factors.get("domain_factor", 0.0)
    logo_factor = score_factors.get("logo_factor", 0.0)
    phish_factor = score_factors.get("phish_factor", 0.0)
    listing_factor = score_factors.get("listing_factor", 0.0)
    social_factor = score_factors.get("social_factor", 0.0)
    notes_factor = score_factors.get("notes_factor", 0.0)
    intent_discount = score_factors.get("intent_discount", 0.0)

    domain_items = case_data.get("flagged_domains", [])
    if domain_items or weights.get("domain", 0) > 0:
        pdf.cell(60, 6, "Domain Typo-Squatting Risk", border=1)
        pdf.cell(45, 6, f"{weights.get('domain', 25.0):.1f}%", border=1)
        pdf.cell(45, 6, f"{domain_factor:.1f} pts", border=1)
        pdf.cell(40, 6, f"{len(domain_items)} domain(s)", border=1, ln=True)

    logo_items = case_data.get("flagged_logos", [])
    if logo_items or weights.get("logo", 0) > 0:
        pdf.cell(60, 6, "Logo Hash Likeness", border=1)
        pdf.cell(45, 6, f"{weights.get('logo', 25.0):.1f}%", border=1)
        pdf.cell(45, 6, f"{logo_factor:.1f} pts", border=1)
        pdf.cell(40, 6, f"{len(logo_items)} logo match(es)", border=1, ln=True)

    phish_items = case_data.get("visual_phishing", [])
    if phish_items or weights.get("phish", 0) > 0:
        pdf.cell(60, 6, "Visual Phishing Detection", border=1)
        pdf.cell(45, 6, f"{weights.get('phish', 20.0):.1f}%", border=1)
        pdf.cell(45, 6, f"{phish_factor:.1f} pts", border=1)
        pdf.cell(40, 6, f"{len(phish_items)} visual check(s)", border=1, ln=True)

    listing_items = case_data.get("flagged_listings", [])
    if listing_items or weights.get("listing", 0) > 0:
        pdf.cell(60, 6, "Marketplace Listing Risk", border=1)
        pdf.cell(45, 6, f"{weights.get('listing', 15.0):.1f}%", border=1)
        pdf.cell(45, 6, f"{listing_factor:.1f} pts", border=1)
        pdf.cell(40, 6, f"{len(listing_items)} listing(s)", border=1, ln=True)


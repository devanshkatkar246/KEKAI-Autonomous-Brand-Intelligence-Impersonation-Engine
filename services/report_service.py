        pdf.set_font("Helvetica", "B", 12)
        pdf.set_text_color(10, 10, 10)
        pdf.cell(0, 8, _latin1_safe(f"3. Flagged Domain Evidence ({len(domain_items)} item(s))"), ln=True)

        pdf.set_font("Helvetica", "B", 9)
        pdf.set_text_color(255, 255, 255)
        pdf.cell(50, 6, "Permutation Domain", border=1, fill=True)
        pdf.cell(30, 6, "Fuzzer Type", border=1, fill=True)
        pdf.cell(20, 6, "Reg.", border=1, fill=True)
        pdf.cell(50, 6, "Intent Classification", border=1, fill=True)
        pdf.cell(40, 6, "IP Address", border=1, fill=True, ln=True)


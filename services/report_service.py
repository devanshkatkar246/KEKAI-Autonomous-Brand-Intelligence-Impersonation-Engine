            pdf.set_font("Helvetica", "B", 9)
            pdf.set_text_color(255, 255, 255)
            pdf.cell(45, 6, "Timestamp (UTC)", border=1, fill=True)
            pdf.cell(35, 6, "Event Type", border=1, fill=True)
            pdf.cell(110, 6, "Description & Audit Rationale", border=1, fill=True, ln=True)

            pdf.set_font("Helvetica", "", 8)
            pdf.set_text_color(51, 65, 85)
